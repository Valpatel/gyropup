"""Generate firmware/balance/include/gp/gp_limits.h: the leg's protection limits from exports/leg/limits.json.

    python -m sim.leg_limits [--sweep]                   # exports/leg/limits.json (docs/leg-protection.md)
    python firmware/balance/tools/gen_limits.py          # -> firmware/balance/include/gp/gp_limits.h
    python firmware/balance/tools/gen_limits.py --check  # exit 1 if the committed header differs from a fresh one

Standard library only (CI runs --check). Every number is the JSON's: the torque per build profile (the PLA bench leg,
the robot's PA6-CF + 6061 leg), the soft stops, the measured-angle window and the commanded leg-length window by lean.
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FW = HERE.parent
R = FW.parents[1]
SRC = R / 'exports' / 'leg' / 'limits.json'
OUT = FW / 'include' / 'gp' / 'gp_limits.h'


def f(v: float) -> str:
    s = f'{float(v):.9g}'
    if s in ('-0', '0'):
        s = '0'
    if '.' not in s and 'e' not in s:
        s += '.0'
    return s + 'f'


def generate(d: dict) -> str:
    L = []
    w = L.append
    rb, pl = d['profiles']['robot'], d['profiles']['pla_bench']
    ss = d['soft_stop']
    win = [r for r in d['command']['window'] if r[1] is not None]
    w('/* GENERATED by firmware/balance/tools/gen_limits.py from exports/leg/limits.json (python -m sim.leg_limits).')
    w(' * Do not edit: docs/leg-protection.md derives every number; re-run both when the FEA, the stops or the motor change. */')
    w('#ifndef GP_LIMITS_H')
    w('#define GP_LIMITS_H')
    w('')
    w('/* the leg build each torque set belongs to (gp_config_default: the robot profile is always the robot\'s leg; the')
    w(' * rig profile takes GP_RIG_BUILD, the PLA bench leg unless the build says otherwise: cmake -DGP_RIG_BUILD=robot) */')
    w('#define GP_BUILD_PLA_BENCH 0')
    w('#define GP_BUILD_ROBOT 1')
    w('#ifndef GP_RIG_BUILD')
    w('#define GP_RIG_BUILD GP_BUILD_PLA_BENCH')
    w('#endif')
    w('')
    for key, p, gov in (('ROBOT', rb, f"every day: {rb['everyday_governing']['part']} {rb['everyday_governing']['case']}; "
                                       f"peak: {rb['peak_governing']['part']} {rb['peak_governing']['case']}"),
                        ('PLA', pl, f"the motor-day derating's PLA cap; first failure {pl['first_failure']['row']} at "
                                    f"{pl['first_failure']['cap_nm']:g} N m")):
        w(f'/* {p["title"]}: {gov} */')
        w(f'#define GP_LIM_{key}_EVERYDAY_NM {f(p["everyday_nm"])}   /* any pose: the cap outside the jump\'s push */')
        w(f'#define GP_LIM_{key}_PEAK_NM {f(p["peak_nm"])}       /* the jump\'s push only, at most GP_LIM_PEAK_MAX_S */')
        w(f'#define GP_LIM_{key}_MOTOR_NM {f(p["motor_limit_torque_nm"])}      /* each RS-04\'s limit_torque (0x700B), written at boot */')
        w('')
    w(f'#define GP_LIM_PEAK_MAX_S {f(rb["peak_max_s"])}')
    w(f'#define GP_LIM_RMS_NM {f(rb["rms_nm"])}             /* the continuous limit: {"PENDING #195: " if rb["rms_pending"] else ""}the RS-04 stall table\'s rated row */')
    w(f'#define GP_LIM_RMS_TAU_S {f(rb["rms_tau_s"])}          /* the mean square\'s time constant: the winding\'s R_wc x C_w */')
    w(f'#define GP_LIM_JUMP_HOT 0.8f              /* no jump while a motor\'s rms is over this share of GP_LIM_RMS_NM */')
    w('')
    w('/* the soft stops (sim/leg_limits.py soft_stop): no torque into a stop inside the margin; inside the zone, approaching')
    w(' * faster than the stop takes at the every-day torque brakes with kd x the excess */')
    w(f'#define GP_LIM_SOFT_MARGIN_RAD {f(math.radians(ss["margin_deg"]))}')
    w(f'#define GP_LIM_SOFT_ZONE_RAD {f(math.radians(ss["zone_deg"]))}')
    w(f'#define GP_LIM_SOFT_KD {f(ss["kd_nm_s_per_rad"])}')
    w(f'#define GP_LIM_STOP_K {f(ss["stop_k_nm_per_rad"])}           /* N m/rad: the TPU sleeve at the motor (sim/leg_rig.py) */')
    w(f'#define GP_LIM_J_MOTOR {f(ss["j_kg_m2"])}          /* kg m^2: the rotor reflected + the upper link */')
    w(f'#define GP_LIM_ANGLE_WINDOW_RAD {f(math.radians(d["angle_window_deg"]))}   /* a motor this far past a hard stop: limp */')
    w('')
    w(f'/* the commanded leg length by lean (rad, + = wheel forward): inside the stops by the soft margin and at least')
    w(f' * {d["command"]["dead_point_min_deg"]:g} deg from a dead point */')
    w(f'#define GP_LIM_WIN_N {len(win)}')
    w('#ifdef GP_LIMITS_TABLES')
    w('static const float gp_lim_window[GP_LIM_WIN_N][3] = {')
    for lean, lo, hi in win:
        w(f'    {{{f(lean)}, {f(lo)}, {f(hi)}}},')
    w('};')
    w('#endif')
    w('')
    w('#endif')
    return '\n'.join(L) + '\n'


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    text = generate(json.loads(SRC.read_text()))
    if a.check:
        same = OUT.exists() and OUT.read_text() == text
        print('gp_limits.h is ' + ('current' if same else 'STALE: re-run tools/gen_limits.py'))
        return 0 if same else 1
    OUT.write_text(text)
    print(f'wrote {OUT.relative_to(R)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
